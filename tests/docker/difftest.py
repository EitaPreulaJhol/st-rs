#!/usr/bin/env python3
"""Differential fuzzer: compare Rust st screen dumps with the C original.

Usage: difftest.py RUST_BIN C_BIN WORKDIR CASES [SEED]

Both programs are run under the same X display (Xvfb in Docker).  The child
emits the generated byte stream, disables terminal echo, and finally asks st to
dump its screen via the printer mechanism (CSI 0 i).  The dumps must match
byte for byte.
"""

import os
import random
import subprocess
import sys

ECHO_OFF = b"\x1b[4i"
TRIGGER = b"\x1b[0i"


def run(binpath, tag, seqfile, workdir):
    dump = os.path.join(workdir, f"dump_{tag}.txt")
    sizef = os.path.join(workdir, f"size_{tag}.txt")
    for path in (dump, sizef):
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass
    cmd = (
        f'stty raw -echo; stty size > {sizef}; '
        f'printf "\\033[4i"; cat {seqfile}; printf "\\033[0i"; sleep 0.15'
    )
    proc = subprocess.run(
        [binpath, "-g", "80x24", "-o", dump, "-e", "sh", "-c", cmd],
        stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=20,
    )
    data = open(dump, "rb").read() if os.path.exists(dump) else b""
    size = open(sizef).read().strip() if os.path.exists(sizef) else ""
    return proc.returncode, proc.stderr, data, size


def gen(rng, n):
    finals = "ABCDEFGHJKLMPSTXZ@`abcdefglmrsu"
    out = bytearray()
    for _ in range(n):
        k = rng.randrange(18)
        if k == 0:
            out += bytes(rng.choice(b"abcXYZ019 .,;:!@#$%^&*()[]{}<>/\\|~`'\"-_=+")
                         for _ in range(rng.randrange(1, 20)))
        elif k == 1:
            out += bytes([rng.choice([0x0a, 0x0d, 0x09, 0x08, 0x0b, 0x0c,
                                      0x0e, 0x0f, 0x07])])
        elif k == 2:
            nargs = rng.randrange(0, 4)
            vals = [str(rng.choice([0, 1, 2, 3, 5, 8, 10, 20, 40, 80, 255, 999]))
                    for _ in range(nargs)]
            out += b"\x1b[" + ";".join(vals).encode() + rng.choice(finals).encode()
        elif k == 3:
            vals = [str(rng.choice([0, 1, 2, 3, 4, 5, 7, 8, 9, 22, 23, 24, 25,
                                    27, 28, 29, 30, 31, 32, 37, 39, 40, 41, 42,
                                    47, 49, 90, 91, 97, 100, 107]))
                    for _ in range(rng.randrange(1, 5))]
            out += b"\x1b[" + ";".join(vals).encode() + b"m"
        elif k == 4:
            r, g, b = (rng.randrange(256) for _ in range(3))
            choice = rng.randrange(3)
            if choice == 0:
                out += f"\x1b[38;2;{r};{g};{b}m".encode()
            elif choice == 1:
                out += f"\x1b[48;2;{r};{g};{b}m".encode()
            else:
                out += f"\x1b[38;5;{r % 256}m".encode()
        elif k == 5:
            out += b"\x1b" + bytes([rng.choice(b"78DEHMZ=>(B)0*+#8%G")])
        elif k == 6:
            priv = rng.choice(["", "?"])
            vals = [str(rng.choice([1, 5, 6, 7, 9, 25, 47, 1000, 1002, 1003,
                                    1004, 1006, 1034, 1047, 1048, 1049, 2004]))]
            out += b"\x1b[" + priv.encode() + ";".join(vals).encode() + \
                   bytes([rng.choice(b"hl")])
        elif k == 7:
            out += rng.choice([
                b"\x1b]0;title\x07", b"\x1b]1;icon\x07", b"\x1b]2;title\x1b\\",
                b"\x1b]10;?\x07", b"\x1b]11;#112233\x07", b"\x1b]4;1;#ff0000\x07",
                b"\x1b]104\x07", b"\x1b]110\x07", b"\x1b]52;c;aGVsbG8=\x07",
            ])
        elif k == 8:
            out += rng.choice(["é", "世", "界", "☃", "π", "≠", "·"]).encode()
        elif k == 9:
            out += rng.choice([
                b"\x1b[H", b"\x1b[2J", b"\x1b[K", b"\x1b[1K", b"\x1b[2K",
                b"\x1b[P", b"\x1b[@", b"\x1b[L", b"\x1b[M", b"\x1b[S", b"\x1b[T",
                b"\x1b[4h", b"\x1b[4l", b"\x1b[?7h", b"\x1b[?7l",
                b"\x1b[1;1H", b"\x1b[5;10H", b"\x1b[2;3r", b"\x1b[r",
                b"\x1b7", b"\x1b8", b"\x1bD", b"\x1bE", b"\x1bM",
            ])
        elif k == 10:
            out += rng.choice([b"\t", b"\x1b[3g", b"\x1bH", b"\x1b[2I",
                               b"\x1b[1Z"])
        elif k == 11:
            out += b"\x1b[?1049h" + \
                   bytes(rng.choice(b"alt text") for _ in range(6)) + \
                   b"\x1b[?1049l"
        elif k == 12:
            out += b"\x1b(0" + bytes([rng.randrange(0x41, 0x7f)]) + b"\x1b(B"
        elif k == 13:
            out += rng.choice([b"\x1b#8", b"\x1b%G", b"\x1b%@", b"\x1b%G",
                               b"\x1b(B", b"\x1b)0", b"\x1b*A", b"\x1b+B"])
        elif k == 14:
            out += bytes(rng.randrange(256) for _ in range(rng.randrange(1, 10)))
        elif k == 15:
            choice = rng.randrange(3)
            if choice == 0:
                out += f"\x1b[38:5:{rng.randrange(256)}m".encode()
            elif choice == 1:
                out += (f"\x1b[48:2:{rng.randrange(256)}:"
                        f"{rng.randrange(256)}:{rng.randrange(256)}m").encode()
            else:
                out += b"\x1b[4:3m"
        elif k == 16:
            out += bytes([rng.choice([0x80, 0x84, 0x85, 0x88, 0x8a, 0x8d,
                                      0x90, 0x9a, 0x9b, 0x9c, 0x9d, 0x9e,
                                      0x9f])])
            if rng.randrange(3) == 0:
                out += b"xyz\x07"
        else:
            out += rng.choice([
                b"\x1b]4;1;?\x07", b"\x1b]4;?\x07", b"\x1b]104;1\x07",
                b"\x1b]112\x07", b"\x1b]111\x07", b"\x1b]12;#abcdef\x07",
                b"\x1b]0;a;b;c\x07", b"\x1b]2;\xe4\xb8\x96\xe7\x95\x8c\x07",
                b"\x1b]52;c;!!invalid!!\x07", b"\x1b]k;title\x07",
                b"\x1b]4;258;#101010\x07", b"\x1b]104\x07",
            ])

    data = bytes(out)
    while TRIGGER in data:
        data = data.replace(TRIGGER, b"\x1b[0j", 1)
    return data


def main(argv):
    if len(argv) < 5:
        print(__doc__)
        return 2
    rust, cst, workdir, cases = argv[1], argv[2], argv[3], int(argv[4])
    seed = int(argv[5], 0) if len(argv) > 5 else 0xC0FFEE
    os.makedirs(workdir, exist_ok=True)
    seqfile = os.path.join(workdir, "seq.bin")
    rng = random.Random(seed)
    fails = 0

    for case in range(cases):
        seq = gen(rng, rng.randrange(3, 12))
        with open(seqfile, "wb") as f:
            f.write(seq)

        results = {}
        for attempt in range(6):
            bad = False
            for tag, binary in (("r", rust), ("c", cst)):
                rc, err, data, size = run(binary, tag, seqfile, workdir)
                if not data.startswith(ECHO_OFF):
                    print(f"case {case}: {tag} output does not start with "
                          f"the printer toggle")
                    print(" seq:", seq)
                    print(" got:", data[:80])
                    print(" err:", err[:400])
                    fails += 1
                    bad = True
                    break
                results[tag] = (rc, data[len(ECHO_OFF):], size)
            if bad:
                break
            if results["r"][2] != results["c"][2]:
                # The window manager (absent under Xvfb, but be robust) could
                # have changed the terminal size between runs; retry.
                continue
            if results["r"][1] != results["c"][1] or results["r"][0] != results["c"][0]:
                fails += 1
                print(f"case {case}: MISMATCH (rc {results['r'][0]} vs "
                      f"{results['c'][0]}, size {results['r'][2]}/"
                      f"{results['c'][2]})")
                print(" seq:", seq)
                print(" rust:", results["r"][1][:300])
                print(" c:   ", results["c"][1][:300])
                with open(os.path.join(workdir, f"fail_{case}.seq"), "wb") as f:
                    f.write(seq)
            break
        else:
            print(f"case {case}: could not obtain matching terminal sizes, "
                  f"skipping")
        if fails > 5:
            break

    print(f"differential fuzz: {cases} cases, {fails} failures")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
